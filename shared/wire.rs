//! Allocation-free HID/IOCTL contract shared by the kernel and user-mode feeder.
//! Physical sensor precision remains 10-bit; the virtual pressure range is 0..4097.

pub const REPORT_LEN: usize = 10;
pub const IOCTL_SUBMIT: u32 = (0x22 << 16) | (2 << 14) | (0x800 << 2);
pub const MAX_X: u16 = 14720;
pub const MAX_Y: u16 = 9200;
pub const PRESSURE_MAX: u16 = 4097;
pub const REPORT_DESCRIPTOR: &[u8] = &[
    0x05, 0x0d, 0x09, 0x02, 0xa1, 0x01, 0x85, 0x01, 0x09, 0x20, 0xa1, 0x00, 0x09, 0x42, 0x09, 0x44,
    0x09, 0x3c, 0x09, 0x45, 0x09, 0x32, // five pen flags
    0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x05, 0x81, 0x02, 0x75, 0x03, 0x95, 0x01, 0x81,
    0x03, // padding
    0x05, 0x01, 0x09, 0x30, 0x15, 0x00, 0x26, 0x80, 0x39, 0x75, 0x10, 0x95, 0x01, 0x81, 0x02, 0x09,
    0x31, 0x26, 0xf0, 0x23, 0x81, 0x02, // Y 0..9200
    0x05, 0x0d, 0x09, 0x30, 0x26, 0x01, 0x10, 0x81, 0x02, // pressure 0..4097
    0x09, 0x3d, 0x09, 0x3e, 0x15, 0xc4, 0x25, 0x3c, 0x75, 0x08, 0x95, 0x02, 0x81,
    0x02, // signed X/Y tilt -60..60
    0xc0, 0xc0,
];

pub fn valid_report(b: &[u8]) -> bool {
    if b.len() != REPORT_LEN || b[0] != 1 || b[1] & 0xe0 != 0 {
        return false;
    }
    let pressure = u16::from_le_bytes([b[6], b[7]]);
    let tip = b[1] & 1 != 0;
    let range = b[1] & 16 != 0;
    u16::from_le_bytes([b[2], b[3]]) <= MAX_X
        && u16::from_le_bytes([b[4], b[5]]) <= MAX_Y
        && pressure <= PRESSURE_MAX
        && (-60..=60).contains(&(b[8] as i8))
        && (-60..=60).contains(&(b[9] as i8))
        && (!tip || range)
        && ((tip && range) || pressure == 0)
}
